import { test, expect } from './fixtures'
import { createTestAccount, logIn, signOutFromHeader } from './helpers'

test('views, updates and persists the profile and header', async ({ page }) => {
  const account = await createTestAccount(page)
  await page.goto('/profile')
  await expect(page.getByLabel('Display name')).toHaveValue(account.name)
  await expect(page.getByLabel('Avatar initials')).toHaveValue('PT')
  await expect(page.getByText(account.email, { exact: true })).toBeVisible()
  await page.getByLabel('Display name').fill('Updated Name')
  await page.getByLabel('Avatar initials').fill('un')
  await page.getByRole('button', { name: 'Avatar color 4' }).click()
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Changes saved.' })).toBeVisible()
  await expect(page.getByRole('banner')).toContainText('Updated Name', { timeout: 2000 })
  await expect(page.getByRole('banner').locator('[aria-hidden="true"]').first()).toHaveCSS('background-color', 'rgb(245, 158, 11)')
  await page.reload()
  await expect(page.getByLabel('Display name')).toHaveValue('Updated Name')
  await expect(page.getByLabel('Avatar initials')).toHaveValue('UN')
  await expect(page.getByRole('button', { name: 'Avatar color 4' })).toHaveAttribute('aria-pressed', 'true')
})

test('rejects an empty display name without navigating away', async ({ page }) => {
  await createTestAccount(page)
  await page.goto('/profile')
  await page.getByLabel('Display name').fill('')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('Display name is required.', { exact: true })).toBeVisible()
  await expect(page).toHaveURL('/profile')
})

test('preserves the protected return URL after signing in', async ({ page }) => {
  await page.goto('/profile')
  await expect(page).toHaveURL('/sign-in?callbackUrl=%2Fprofile')
  await logIn(page)
  await expect(page).toHaveURL('/profile')
  await expect(page.getByLabel('Display name')).toHaveValue('Alex Morgan')
})

test('changes password while retaining the session, rejects old password and accepts new', async ({ page }) => {
  const account = await createTestAccount(page)
  await page.goto('/profile')
  await page.getByLabel('Current password', { exact: true }).fill(account.password)
  await page.getByLabel('New password', { exact: true }).fill('newpassword456')
  await page.getByLabel('Confirm new password', { exact: true }).fill('newpassword456')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Password updated.' })).toBeVisible()
  await expect(page).toHaveURL('/profile')
  await expect(page.getByLabel('Current password', { exact: true })).toHaveValue('')
  await signOutFromHeader(page)
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Password', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByText('Invalid email or password.', { exact: true })).toBeVisible()
  await page.getByLabel('Password', { exact: true }).fill('newpassword456')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL('/')
})

test('rejects wrong current password, short password and mismatched confirmation', async ({ page }) => {
  await createTestAccount(page)
  await page.goto('/profile')
  await page.getByLabel('Current password', { exact: true }).fill('wrongpassword')
  await page.getByLabel('New password', { exact: true }).fill('newpassword456')
  await page.getByLabel('Confirm new password', { exact: true }).fill('newpassword456')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(page.getByLabel('Current password', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('Current password is incorrect.', { exact: true }).first()).toBeVisible()
  await page.getByLabel('Current password', { exact: true }).fill('password123')
  await page.getByLabel('New password', { exact: true }).fill('short')
  await page.getByLabel('Confirm new password', { exact: true }).fill('short')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(page.getByText('Password must be at least 8 characters.', { exact: true })).toBeVisible()
  await page.getByLabel('New password', { exact: true }).fill('newpassword456')
  await page.getByRole('button', { name: 'Update password', exact: true }).click()
  await expect(page.getByText('Passwords do not match.', { exact: true })).toBeVisible()
  await expect(page).toHaveURL('/profile')
})

test('signing out in another tab prevents a stale profile form from saving', async ({ page, context }) => {
  await createTestAccount(page)
  await page.goto('/profile')
  const otherTab = await context.newPage()
  await otherTab.goto('/')
  await signOutFromHeader(otherTab)
  await page.getByLabel('Display name').fill('Stale Edit')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page).toHaveURL(/\/sign-in\?/)
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
})
